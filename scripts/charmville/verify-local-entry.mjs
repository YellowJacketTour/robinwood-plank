import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import { verifyControls, verifyGamepadAction } from './verify-controls.mjs';
import { mkdir } from 'node:fs/promises';
const base = process.env.CHARMVILLE_TEST_BASE_URL || 'http://localhost:3017';
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw Error('Local verification only');
const browser = await chromium.launch({headless:true});
try {
  const page = await browser.newPage({viewport:{width:1280,height:1100},hasTouch:true});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));page.on('console',message=>{if(message.type()==='error')errors.push(message.text());});
  await mkdir('.dream-loop',{recursive:true});
  await page.addInitScript(() => localStorage.setItem('plankspace-last-verified-wallet','0x1111111111111111111111111111111111111111'));
  await page.goto(base+'/charmville/play');
  await page.getByRole('button',{name:'Start playing',exact:true}).click();
  const porch = page.getByRole('region',{name:'Charmville porch'});
  await porch.getByRole('button',{name:'Claim your lot',exact:true}).click();
  await page.locator('[data-plot="0"][data-stage="ripe"]').waitFor();
  await verifyControls(page);
  await porch.getByRole('button',{name:'Gather',exact:true}).click();
  const bag = page.getByRole('dialog',{name:'Satchel'});
  await bag.waitFor();
  await page.setViewportSize({width:1536,height:1024});
  await page.screenshot({path:'.dream-loop/local-entry-satchel-1536.png'});
  await bag.getByRole('button',{name:'Back to garden · plant stalk',exact:true}).click();
  await porch.getByRole('button',{name:'Plant here',exact:true}).click();
  await page.locator('[data-plot="0"][data-stage="seedling"]').waitFor();
  await page.reload();
  await page.locator('[data-plot="0"][data-stage="seedling"]').waitFor();
  await verifyGamepadAction(page);
  await page.setViewportSize({width:1536,height:1024});
  await porch.scrollIntoViewIfNeeded();
  await page.screenshot({path:'.dream-loop/local-entry-desktop-1536.png'});
  assert.equal(await page.evaluate(()=>localStorage.getItem('plankspace-last-verified-wallet')),'0x1111111111111111111111111111111111111111');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.dream-loop/local-entry-mobile.png',fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth > innerWidth),false);
  await page.goto(base+'/u/charmville_showcase');
  assert.equal(await page.evaluate(()=>localStorage.getItem('plankspace-last-verified-wallet')),'0x1111111111111111111111111111111111111111');
  console.log('Local normal-browser entry: claim, harvest, replant, reload, mobile fit and remembered wallet isolation passed.');
  assert.deepEqual(errors,[],'Browser must not log runtime or console errors');
} finally {await browser.close();}
