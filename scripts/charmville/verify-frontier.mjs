import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const output=process.env.CHARMVILLE_FRONTIER_OUTPUT||'.dream-loop/frontier';
await mkdir(output,{recursive:true});
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto('http://localhost:3017/charmville/frontier',{waitUntil:'domcontentloaded',timeout:120000});
 await page.getByRole('button',{name:'Swing sword',exact:true}).waitFor({timeout:120000});
 await page.waitForTimeout(7000);
 await page.screenshot({path:output+'/frontier-desktop.png',fullPage:true});
 const world=page.locator('[aria-label="Playable Charmville district"]');
 await world.focus();await page.keyboard.down('s');await page.waitForTimeout(650);await page.keyboard.up('s');await page.keyboard.press('Space');
 await page.waitForTimeout(500);
 const cuttings=await page.locator('small').filter({hasText:'Meadow cuttings'}).textContent();
 if(/cuttings 0 /.test(cuttings))throw Error('Sword did not clear grass after movement');
 await page.getByRole('button',{name:'Place blossom',exact:true}).click();
 await world.locator('canvas').click({position:{x:650,y:450}});
 await page.getByRole('button',{name:'Save scenery',exact:true}).click();
 const draft=await page.evaluate(()=>JSON.parse(localStorage.getItem('charmville-frontier-draft-1')));
 if(draft.length!==25)throw Error('Placement not saved');
 await page.getByRole('button',{name:'UFO visual event',exact:true}).click();await page.waitForTimeout(1500);
 await page.screenshot({path:output+'/frontier-ufo.png',fullPage:true});
 await page.getByRole('button',{name:/Charm atlas ·/}).click();
 await page.getByRole('textbox',{name:'Search charms'}).fill('alien');
 await page.getByRole('button',{name:/alien.*Discover identity/}).click();
 await page.getByText('Source network: osmo-test-5').waitFor();
 await page.getByRole('button',{name:'Close charm details'}).click();
 await page.getByRole('button',{name:/Creator library ·/}).click();
 await page.getByRole('combobox',{name:'Asset source'}).selectOption('solarus-trillium');
 await page.getByText('871 matching files',{exact:false}).waitFor({timeout:30000});
 await page.setViewportSize({width:390,height:844});await page.getByRole('button',{name:'Explore the district'}).click();
 await page.waitForTimeout(1500);await page.screenshot({path:output+'/frontier-mobile.png',fullPage:true});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1))throw Error('Mobile horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 await writeFile(output+'/verification.json',JSON.stringify({passed:true,cuttings,sceneryObjects:draft.length,checks:['movement','sword grass cutting','placement and device persistence','UFO camera','78-entry atlas search','source filter','390px layout'],pageErrors:errors},null,2));
 console.log('Frontier browser checks passed',cuttings);
}finally{await browser.close();}
